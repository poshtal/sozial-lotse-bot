/** Что ядро отдаёт оболочке (консоли или Telegram). */
export class BotReply {
  /** Сообщения по порядку. */
  messages: string[] = [];
  /** Варианты ответа: оболочка показывает их кнопками. */
  options: string[] = [];
  /** Разговор закончен или стёрт: оболочка предлагает начать заново. */
  finished: boolean = false;
  /**
   * Человек попросил всё забыть: оболочка, если умеет, убирает и саму
   * переписку с экрана. Память ядра к этому моменту уже пуста.
   */
  eraseChat: boolean = false;
  /**
   * Это ответ на вопрос человека, и он мог прийти с задержкой. Оболочка,
   * если умеет, показывает, на какое именно сообщение отвечает бот.
   */
  answersQuestion: boolean = false;
}
